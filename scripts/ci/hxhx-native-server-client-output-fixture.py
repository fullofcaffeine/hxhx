#!/usr/bin/env python3
"""Exercise native hxhx socket request output and failure isolation.

The fixture starts one native server, sends editor and compiler requests through
the public ``--connect`` client, and checks that compiler-owned output returns to
that client instead of leaking into the server process. A deliberately failing
compile is followed by another successful compile to prove that request failure
does not poison the long-lived process or replace the last good target file.
Separate stdio processes prove that a negative or oversized length receives a
framed protocol error before allocation.
Both transports prove that an expired request returns a cancellation response
without stopping the server, then prove that an explicit shutdown response is
sent before the server exits successfully.
An additional repeated-compile sequence checks that request IDs, cleanup,
source/parser cache reuse, dependency observations, reset behavior, and
generated bytes remain stable as the same process handles more work.
"""

from __future__ import annotations

import argparse
import re
import socket
import struct
import subprocess
import sys
import time
from pathlib import Path
from typing import List, Optional


STABILITY_REQUEST_COUNT = 8


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser()
    parser.add_argument("--hxhx-bin", required=True, type=Path)
    parser.add_argument("--tmpdir", required=True, type=Path)
    return parser.parse_args()


def reserve_port() -> int:
    with socket.socket(socket.AF_INET, socket.SOCK_STREAM) as probe:
        probe.bind(("127.0.0.1", 0))
        return int(probe.getsockname()[1])


def require_occupied_endpoint_is_left_alone(hxhx_bin: Path, base_args: List[str]) -> None:
    """Prove hxhx reports an occupied port without stopping its existing owner."""
    with socket.socket(socket.AF_INET, socket.SOCK_STREAM) as owner:
        owner.setsockopt(socket.SOL_SOCKET, socket.SO_REUSEADDR, 1)
        owner.bind(("127.0.0.1", 0))
        owner.listen(1)
        endpoint = f"127.0.0.1:{owner.getsockname()[1]}"
        result = subprocess.run(
            [str(hxhx_bin), *base_args, "--wait", endpoint],
            capture_output=True,
            text=True,
            timeout=30,
            check=False,
        )
        if result.returncode == 0:
            raise RuntimeError("native server unexpectedly replaced the process owning an occupied endpoint")
        text = result.stdout + result.stderr
        if "wait socket failed" not in text:
            raise RuntimeError(f"occupied endpoint failure was not actionable: {text!r}")
        if owner.fileno() < 0 or owner.getsockname()[1] <= 0:
            raise RuntimeError("native server disturbed the existing endpoint owner")


def run_client(hxhx_bin: Path, base_args: List[str], endpoint: str, request_args: List[str]) -> subprocess.CompletedProcess[str]:
    return subprocess.run(
        [str(hxhx_bin), *base_args, "--connect", endpoint, *request_args],
        capture_output=True,
        text=True,
        timeout=90,
        check=False,
    )


def require_success(result: subprocess.CompletedProcess[str], label: str) -> None:
    if result.returncode != 0:
        raise RuntimeError(
            f"{label} failed (rc={result.returncode}, stdout={result.stdout!r}, stderr={result.stderr!r})"
        )


def compiler_output_without_report(text: str) -> str:
    """Remove the explicitly diagnostic server-report rows before parity comparison."""
    lines = text.replace("\r\n", "\n").splitlines()
    return "\n".join(line for line in lines if not line.startswith("hxhx_server_report."))


def require_compiler_output_equivalent(
    actual: subprocess.CompletedProcess[str],
    expected: subprocess.CompletedProcess[str],
    label: str,
) -> None:
    actual_stdout = compiler_output_without_report(actual.stdout)
    expected_stdout = compiler_output_without_report(expected.stdout)
    actual_stderr = compiler_output_without_report(actual.stderr)
    expected_stderr = compiler_output_without_report(expected.stderr)
    if actual_stdout != expected_stdout or actual_stderr != expected_stderr:
        raise RuntimeError(
            f"{label} compiler output differs from a fresh process "
            f"(actual stdout={actual_stdout!r}, expected stdout={expected_stdout!r}, "
            f"actual stderr={actual_stderr!r}, expected stderr={expected_stderr!r})"
        )


def report_int(result: subprocess.CompletedProcess[str], name: str, label: str) -> int:
    text = result.stdout + result.stderr
    match = re.search(rf"^hxhx_server_report\.{re.escape(name)}=(\d+)$", text, re.MULTILINE)
    if match is None:
        raise RuntimeError(f"{label} is missing integer report field {name!r}: {text!r}")
    return int(match.group(1))


def report_text(result: subprocess.CompletedProcess[str], name: str, label: str) -> str:
    text = result.stdout + result.stderr
    match = re.search(rf"^hxhx_server_report\.{re.escape(name)}=(.*)$", text, re.MULTILINE)
    if match is None:
        raise RuntimeError(f"{label} is missing text report field {name!r}: {text!r}")
    return match.group(1).rstrip("\r")


def require_baseline_report(
    result: subprocess.CompletedProcess[str], label: str, expected_cache: str = "disabled"
) -> int:
    text = result.stdout + result.stderr
    required = [
        f"hxhx_server_report.semantic_cache={expected_cache}",
        "hxhx_server_report.semantic_cache_hits=",
        "hxhx_server_report.semantic_cache_misses=",
        "hxhx_server_report.semantic_cache_entries=",
        "hxhx_server_report.source_hits=",
        "hxhx_server_report.source_misses=",
        "hxhx_server_report.resolution_hits=",
        "hxhx_server_report.resolution_misses=",
        "hxhx_server_report.parser_hits=",
        "hxhx_server_report.parser_misses=",
        "hxhx_server_report.dependency_observation=",
        "hxhx_server_report.cancelled=",
        "hxhx_server_report.output_transaction=",
        "hxhx_server_report.cleanup=ok",
        "hxhx_server_report.phase_count=",
        "hxhx_server_report.phase[0].name=request-init",
        "hxhx_server_report.phase[0].elapsed_ms=",
        "hxhx_server_report.elapsed_ms=",
    ]
    for marker in required:
        if marker not in text:
            raise RuntimeError(f"{label} is missing baseline report marker {marker!r}: {text!r}")
    match = re.search(r"hxhx_server_report\.request_id=(\d+)", text)
    if match is None:
        raise RuntimeError(f"{label} is missing its request ID: {text!r}")
    return int(match.group(1))


def require_output_transaction(
    result: subprocess.CompletedProcess[str], label: str, expected: str
) -> None:
    marker = f"hxhx_server_report.output_transaction={expected}"
    text = result.stdout + result.stderr
    if marker not in text:
        raise RuntimeError(f"{label} is missing output transaction marker {marker!r}: {text!r}")


def require_cancellation_report(result: subprocess.CompletedProcess[str], label: str) -> int:
    request_id = require_baseline_report(result, label, "source-resolution-parser")
    text = result.stdout + result.stderr
    required = [
        "request cancelled [deadline-exceeded] at request-dispatch",
        "hxhx_server_report.cancelled=1",
        "hxhx_server_report.cancellation_reason=deadline-exceeded",
        "hxhx_server_report.cancellation_stage=request-dispatch",
    ]
    for marker in required:
        if marker not in text:
            raise RuntimeError(f"{label} is missing cancellation marker {marker!r}: {text!r}")
    require_output_transaction(result, label, "not_started")
    return request_id


def require_rejected_stdio_length(
    hxhx_bin: Path, output_path: Path, declared_length: int, expected: str
) -> None:
    result = subprocess.run(
        [str(hxhx_bin), "--hxhx-no-run", "--js", str(output_path), "--wait", "stdio"],
        input=struct.pack("<i", declared_length),
        capture_output=True,
        timeout=30,
        check=False,
    )
    if result.returncode == 0:
        raise RuntimeError(f"invalid stdio frame length {declared_length} unexpectedly succeeded")
    if result.stdout:
        raise RuntimeError(f"invalid stdio frame wrote unexpected stdout: {result.stdout!r}")
    if len(result.stderr) < 4:
        raise RuntimeError(f"invalid stdio frame omitted its response header: {result.stderr!r}")
    response_length = struct.unpack("<I", result.stderr[:4])[0]
    response = result.stderr[4:]
    if len(response) != response_length:
        raise RuntimeError(
            f"invalid stdio response length mismatch: header={response_length}, body={len(response)}"
        )
    text = response.decode("utf-8", errors="replace")
    if expected not in text or "\x02" not in text:
        raise RuntimeError(f"invalid stdio frame lacked its protocol error: {text!r}")


def require_stdio_shutdown(hxhx_bin: Path, output_path: Path) -> None:
    payload = b"--hxhx-server-control\nshutdown\n"
    result = subprocess.run(
        [str(hxhx_bin), "--hxhx-no-run", "--js", str(output_path), "--wait", "stdio"],
        input=struct.pack("<I", len(payload)) + payload,
        capture_output=True,
        timeout=30,
        check=False,
    )
    if result.returncode != 0 or result.stdout:
        raise RuntimeError(
            f"stdio shutdown failed (rc={result.returncode}, stdout={result.stdout!r}, stderr={result.stderr!r})"
        )
    if len(result.stderr) < 4:
        raise RuntimeError(f"stdio shutdown omitted its response header: {result.stderr!r}")
    response_length = struct.unpack("<I", result.stderr[:4])[0]
    response = result.stderr[4:]
    if len(response) != response_length:
        raise RuntimeError(
            f"stdio shutdown response length mismatch: header={response_length}, body={len(response)}"
        )
    if b"hxhx_server_control.shutdown=ok" not in response or b"\x02" in response:
        raise RuntimeError(f"stdio shutdown returned an unexpected response: {response!r}")
    if output_path.exists():
        raise RuntimeError("stdio shutdown unexpectedly produced target output")


def require_stdio_cancellation(hxhx_bin: Path, output_path: Path) -> None:
    payload = b"--hxhx-server-timeout-ms\n0\n-main\nNeverCompiled\n"
    result = subprocess.run(
        [
            str(hxhx_bin),
            "--hxhx-no-run",
            "--hxhx-server-report",
            "--js",
            str(output_path),
            "--wait",
            "stdio",
        ],
        input=struct.pack("<I", len(payload)) + payload,
        capture_output=True,
        timeout=30,
        check=False,
    )
    if result.returncode != 0 or result.stdout:
        raise RuntimeError(
            f"stdio cancellation failed (rc={result.returncode}, stdout={result.stdout!r}, stderr={result.stderr!r})"
        )
    if len(result.stderr) < 4:
        raise RuntimeError(f"stdio cancellation omitted its response header: {result.stderr!r}")
    response_length = struct.unpack("<I", result.stderr[:4])[0]
    response = result.stderr[4:]
    if len(response) != response_length:
        raise RuntimeError(
            f"stdio cancellation response length mismatch: header={response_length}, body={len(response)}"
        )
    required = [
        b"request cancelled [deadline-exceeded] at request-dispatch",
        b"hxhx_server_report.cancelled=1",
        b"hxhx_server_report.output_transaction=not_started",
        b"hxhx_server_report.cleanup=ok",
        b"\x02",
    ]
    for marker in required:
        if marker not in response:
            raise RuntimeError(f"stdio cancellation omitted {marker!r}: {response!r}")
    if output_path.exists():
        raise RuntimeError("stdio cancellation unexpectedly produced target output")


def main() -> int:
    args = parse_args()
    hxhx_bin = args.hxhx_bin.resolve()
    tmpdir = args.tmpdir.resolve()
    fixture_root = tmpdir / "native-server-client-output"
    classpath = fixture_root / "src"
    classpath.mkdir(parents=True, exist_ok=True)
    (classpath / "DisplayMain.hx").write_text(
        "class DisplayMain { static function main() {} }\n", encoding="utf-8"
    )
    (classpath / "SocketCompileMain.hx").write_text(
        'class SocketCompileMain { static function main() { Sys.println("socket-compile-ok"); } }\n',
        encoding="utf-8",
    )
    display_source = classpath / "DisplayMain.hx"
    out_dir = fixture_root / "out"
    artifact = out_dir / "main.js"
    server_stdout_path = fixture_root / "server.stdout"
    server_stderr_path = fixture_root / "server.stderr"

    endpoint = f"127.0.0.1:{reserve_port()}"
    base_args = ["--hxhx-no-run", "--hxhx-server-report", "--js", str(artifact)]
    request_ids: List[int] = []
    stability_elapsed_ms: List[int] = []

    direct_success = subprocess.run(
        [str(hxhx_bin), *base_args, "-cp", str(classpath), "-main", "SocketCompileMain"],
        capture_output=True,
        text=True,
        timeout=90,
        check=False,
    )
    require_success(direct_success, "fresh-process ordinary compile")
    if require_baseline_report(direct_success, "fresh-process ordinary compile") != 0:
        raise RuntimeError("fresh-process report should use request ID 0")
    direct_elapsed_ms = report_int(direct_success, "elapsed_ms", "fresh-process ordinary compile")
    require_output_transaction(direct_success, "fresh-process ordinary compile", "not_started")
    if not artifact.is_file() or not Path(str(artifact) + ".map").is_file():
        raise RuntimeError("fresh-process ordinary compile did not create JavaScript and its source map")
    direct_artifact_bytes = artifact.read_bytes()
    direct_source_map_bytes = Path(str(artifact) + ".map").read_bytes()
    direct_run = subprocess.run(
        ["node", str(artifact)], capture_output=True, text=True, timeout=30, check=False
    )
    require_success(direct_run, "fresh-process generated program")
    if direct_run.stdout.strip() != "socket-compile-ok":
        raise RuntimeError(f"unexpected fresh-process generated-program output: {direct_run.stdout!r}")

    direct_failure = subprocess.run(
        [str(hxhx_bin), *base_args, "-cp", str(classpath), "-main", "MissingSocketMain"],
        capture_output=True,
        text=True,
        timeout=90,
        check=False,
    )
    if direct_failure.returncode == 0:
        raise RuntimeError("fresh-process missing-main request unexpectedly succeeded")
    if require_baseline_report(direct_failure, "fresh-process missing-main request") != 0:
        raise RuntimeError("fresh-process failure report should use request ID 0")
    require_output_transaction(direct_failure, "fresh-process missing-main request", "not_started")
    if artifact.read_bytes() != direct_artifact_bytes:
        raise RuntimeError("fresh-process failure changed the previous JavaScript artifact")

    test_error: Optional[BaseException] = None
    server_stdout = ""
    server_stderr = ""
    with server_stdout_path.open("w+", encoding="utf-8") as server_stdout_file, server_stderr_path.open(
        "w+", encoding="utf-8"
    ) as server_stderr_file:
        server = subprocess.Popen(
            [str(hxhx_bin), *base_args, "--wait", endpoint],
            stdout=server_stdout_file,
            stderr=server_stderr_file,
            text=True,
        )
        try:
            last: Optional[subprocess.CompletedProcess[str]] = None
            for _ in range(80):
                time.sleep(0.1)
                last = run_client(
                    hxhx_bin,
                    base_args,
                    endpoint,
                    ["--display", f"{display_source}@0@diagnostics", "-cp", str(classpath), "--no-output"],
                )
                if last.returncode == 0:
                    if '[{"diagnostics":[]}]' not in last.stderr:
                        raise RuntimeError(f"unexpected display response: {last.stderr!r}")
                    request_ids.append(require_baseline_report(last, "display request", "source-resolution-parser"))
                    require_output_transaction(last, "display request", "not_started")
                    break
            else:
                raise RuntimeError(
                    "connect request never succeeded "
                    f"(last rc={last.returncode if last else '?'}, stderr={last.stderr if last else ''!r})"
                )

            first_success = run_client(
                hxhx_bin,
                base_args,
                endpoint,
                ["-cp", str(classpath), "-main", "SocketCompileMain"],
            )
            require_success(first_success, "first ordinary socket compile")
            request_ids.append(require_baseline_report(first_success, "first ordinary socket compile", "source-resolution-parser"))
            cold_elapsed_ms = report_int(first_success, "elapsed_ms", "first ordinary socket compile")
            require_output_transaction(first_success, "first ordinary socket compile", "committed")
            if report_text(first_success, "dependency_observation", "first ordinary socket compile") != "enabled":
                raise RuntimeError("cold-server ordinary compile did not enable dependency observation")
            if report_int(first_success, "dependency_previous_snapshot", "first ordinary socket compile") != 0:
                raise RuntimeError("cold-server ordinary compile unexpectedly reused dependency history")
            if report_int(first_success, "dependency_modules", "first ordinary socket compile") <= 0:
                raise RuntimeError("cold-server ordinary compile did not observe typed modules")
            first_dependency_snapshot = report_text(
                first_success, "dependency_snapshot", "first ordinary socket compile"
            )
            if first_dependency_snapshot == "none":
                raise RuntimeError("cold-server ordinary compile omitted its dependency fingerprint")
            if report_int(first_success, "parser_misses", "first ordinary socket compile") <= 0:
                raise RuntimeError("cold-server ordinary compile did not report parser work")
            require_compiler_output_equivalent(first_success, direct_success, "cold-server ordinary compile")
            if "resolved_modules=" not in first_success.stdout or "stage3=ok" not in first_success.stdout:
                raise RuntimeError(f"compiler progress did not reach the first client: {first_success.stdout!r}")
            if not artifact.is_file():
                raise RuntimeError(f"first ordinary socket compile did not create {artifact}")
            if artifact.read_bytes() != direct_artifact_bytes:
                raise RuntimeError("cold-server JavaScript bytes differ from the fresh-process output")
            source_map = Path(str(artifact) + ".map")
            if not source_map.is_file() or source_map.read_bytes() != direct_source_map_bytes:
                raise RuntimeError("cold-server source-map bytes differ from the fresh-process output")

            first_run = subprocess.run(
                ["node", str(artifact)], capture_output=True, text=True, timeout=30, check=False
            )
            require_success(first_run, "first socket-generated program")
            if first_run.stdout.strip() != "socket-compile-ok":
                raise RuntimeError(f"unexpected first generated-program output: {first_run.stdout!r}")

            first_artifact_bytes = artifact.read_bytes()
            cancelled = run_client(
                hxhx_bin,
                base_args,
                endpoint,
                [
                    "--hxhx-server-timeout-ms",
                    "0",
                    "-cp",
                    str(classpath),
                    "-main",
                    "SocketCompileMain",
                ],
            )
            if cancelled.returncode == 0:
                raise RuntimeError("expired socket request unexpectedly succeeded")
            request_ids.append(require_cancellation_report(cancelled, "expired socket request"))
            if not artifact.is_file() or artifact.read_bytes() != first_artifact_bytes:
                raise RuntimeError("expired socket request changed the last successful target artifact")

            expected_failure = run_client(
                hxhx_bin,
                base_args,
                endpoint,
                ["-cp", str(classpath), "-main", "MissingSocketMain"],
            )
            if expected_failure.returncode == 0:
                raise RuntimeError("missing-main socket request unexpectedly succeeded")
            request_ids.append(require_baseline_report(expected_failure, "missing-main socket request", "source-resolution-parser"))
            require_output_transaction(expected_failure, "missing-main socket request", "aborted")
            failure_text = expected_failure.stdout + expected_failure.stderr
            if "resolve failed" not in failure_text or "MissingSocketMain" not in failure_text:
                raise RuntimeError(f"missing-main diagnostic did not reach its client: {failure_text!r}")
            require_compiler_output_equivalent(expected_failure, direct_failure, "warm-server missing-main failure")
            if not artifact.is_file() or artifact.read_bytes() != first_artifact_bytes:
                raise RuntimeError("failed socket request changed the last successful target artifact")

            second_success = run_client(
                hxhx_bin,
                base_args,
                endpoint,
                ["-cp", str(classpath), "-main", "SocketCompileMain"],
            )
            require_success(second_success, "second ordinary socket compile")
            request_ids.append(require_baseline_report(second_success, "second ordinary socket compile", "source-resolution-parser"))
            warm_elapsed_ms = report_int(second_success, "elapsed_ms", "second ordinary socket compile")
            require_output_transaction(second_success, "second ordinary socket compile", "committed")
            if report_int(second_success, "dependency_previous_snapshot", "second ordinary socket compile") != 1:
                raise RuntimeError("repeated server compile did not compare dependency history")
            if report_text(second_success, "dependency_snapshot", "second ordinary socket compile") != first_dependency_snapshot:
                raise RuntimeError("unchanged repeated compile produced a different dependency fingerprint")
            if report_int(second_success, "dependency_public_changes", "second ordinary socket compile") != 0:
                raise RuntimeError("unchanged repeated compile reported a public-interface change")
            if report_int(second_success, "dependency_implementation_changes", "second ordinary socket compile") != 0:
                raise RuntimeError("unchanged repeated compile reported an implementation change")
            if report_int(second_success, "dependency_predicted_invalidations", "second ordinary socket compile") != 0:
                raise RuntimeError("unchanged repeated compile predicted a dependency invalidation")
            if report_int(second_success, "source_hits", "second ordinary socket compile") <= 0:
                raise RuntimeError("repeated server compile did not reuse exact source text")
            if report_int(second_success, "resolution_hits", "second ordinary socket compile") <= 0:
                raise RuntimeError("repeated server compile did not reuse a validated module lookup")
            if report_int(second_success, "parser_hits", "second ordinary socket compile") <= 0:
                raise RuntimeError("repeated server compile did not reuse parsed Haxe syntax")
            require_compiler_output_equivalent(second_success, direct_success, "repeated-server ordinary compile")
            if "resolved_modules=" not in second_success.stdout or "stage3=ok" not in second_success.stdout:
                raise RuntimeError(f"compiler progress did not reach the second client: {second_success.stdout!r}")
            if not artifact.is_file():
                raise RuntimeError(f"second ordinary socket compile did not recreate {artifact}")
            if artifact.read_bytes() != direct_artifact_bytes:
                raise RuntimeError("repeated-server JavaScript bytes differ from the fresh-process output")
            if not source_map.is_file() or source_map.read_bytes() != direct_source_map_bytes:
                raise RuntimeError("repeated-server source-map bytes differ from the fresh-process output")

            second_run = subprocess.run(
                ["node", str(artifact)], capture_output=True, text=True, timeout=30, check=False
            )
            require_success(second_run, "second socket-generated program")
            if second_run.stdout.strip() != "socket-compile-ok":
                raise RuntimeError(f"unexpected second generated-program output: {second_run.stdout!r}")

            for repeat_index in range(STABILITY_REQUEST_COUNT):
                repeated = run_client(
                    hxhx_bin,
                    base_args,
                    endpoint,
                    ["-cp", str(classpath), "-main", "SocketCompileMain"],
                )
                label = f"stability compile {repeat_index + 1}/{STABILITY_REQUEST_COUNT}"
                require_success(repeated, label)
                request_ids.append(require_baseline_report(repeated, label, "source-resolution-parser"))
                stability_elapsed_ms.append(report_int(repeated, "elapsed_ms", label))
                require_output_transaction(repeated, label, "committed")
                if report_int(repeated, "dependency_previous_snapshot", label) != 1:
                    raise RuntimeError(f"{label} did not compare dependency history")
                if report_text(repeated, "dependency_snapshot", label) != first_dependency_snapshot:
                    raise RuntimeError(f"{label} changed the dependency fingerprint without an input edit")
                if report_int(repeated, "dependency_predicted_invalidations", label) != 0:
                    raise RuntimeError(f"{label} predicted invalidations without an input edit")
                require_compiler_output_equivalent(repeated, direct_success, label)
                if artifact.read_bytes() != direct_artifact_bytes:
                    raise RuntimeError(f"{label} JavaScript bytes differ from the fresh-process output")
                if source_map.read_bytes() != direct_source_map_bytes:
                    raise RuntimeError(f"{label} source-map bytes differ from the fresh-process output")

            reset = run_client(
                hxhx_bin,
                base_args,
                endpoint,
                ["--hxhx-server-control", "reset"],
            )
            require_success(reset, "socket server cache reset")
            request_ids.append(require_baseline_report(reset, "socket server cache reset", "source-resolution-parser"))
            require_output_transaction(reset, "socket server cache reset", "not_started")
            if "hxhx_server_control.reset=ok" not in reset.stdout:
                raise RuntimeError(f"socket cache reset did not confirm the control request: {reset.stdout!r}")
            if report_int(reset, "semantic_cache_entries", "socket server cache reset") != 0:
                raise RuntimeError("socket cache reset retained source/parser entries")

            after_reset = run_client(
                hxhx_bin,
                base_args,
                endpoint,
                ["-cp", str(classpath), "-main", "SocketCompileMain"],
            )
            require_success(after_reset, "ordinary socket compile after cache reset")
            request_ids.append(require_baseline_report(after_reset, "ordinary socket compile after cache reset", "source-resolution-parser"))
            after_reset_elapsed_ms = report_int(after_reset, "elapsed_ms", "ordinary socket compile after cache reset")
            require_output_transaction(after_reset, "ordinary socket compile after cache reset", "committed")
            if report_int(after_reset, "dependency_previous_snapshot", "ordinary socket compile after cache reset") != 0:
                raise RuntimeError("first compile after reset retained dependency history")
            if report_int(after_reset, "parser_misses", "ordinary socket compile after cache reset") <= 0:
                raise RuntimeError("first compile after reset did not return to a cold parser cache")
            require_compiler_output_equivalent(after_reset, direct_success, "ordinary socket compile after cache reset")
            if artifact.read_bytes() != direct_artifact_bytes or source_map.read_bytes() != direct_source_map_bytes:
                raise RuntimeError("compile after cache reset differs from the fresh-process output")

            shutdown = run_client(
                hxhx_bin,
                base_args,
                endpoint,
                ["--hxhx-server-control", "shutdown"],
            )
            require_success(shutdown, "socket server shutdown")
            request_ids.append(require_baseline_report(shutdown, "socket server shutdown", "source-resolution-parser"))
            require_output_transaction(shutdown, "socket server shutdown", "not_started")
            if "hxhx_server_control.shutdown=ok" not in shutdown.stdout:
                raise RuntimeError(f"socket shutdown did not confirm the control request: {shutdown.stdout!r}")
            if request_ids != sorted(set(request_ids)):
                raise RuntimeError(f"server request IDs were not unique and increasing: {request_ids!r}")
            server.wait(timeout=5)
            if server.returncode != 0:
                raise RuntimeError(f"socket server exited with {server.returncode} after graceful shutdown")
        except BaseException as error:
            test_error = error
        finally:
            if server.poll() is None:
                server.terminate()
            try:
                server.wait(timeout=5)
            except subprocess.TimeoutExpired:
                server.kill()
                server.wait(timeout=5)
            server_stdout_file.seek(0)
            server_stderr_file.seek(0)
            server_stdout = server_stdout_file.read()
            server_stderr = server_stderr_file.read()

    if test_error is not None:
        raise RuntimeError(
            f"{test_error}\nserver stdout={server_stdout!r}\nserver stderr={server_stderr!r}"
        ) from test_error
    if server_stdout or server_stderr:
        raise RuntimeError(
            "compiler-owned request output leaked into the server process "
            f"(stdout={server_stdout!r}, stderr={server_stderr!r})"
        )
    transaction_residue = sorted(
        str(path)
        for path in fixture_root.rglob("*")
        if path.name.startswith(".hxhx-server-stage-")
        or path.name.startswith(".hxhx-server-backup-")
    )
    if transaction_residue:
        raise RuntimeError(f"native server left output transaction residue: {transaction_residue!r}")

    invalid_stdio_output = fixture_root / "invalid-stdio.js"
    require_rejected_stdio_length(hxhx_bin, invalid_stdio_output, -1, "negative request frame length")
    require_rejected_stdio_length(
        hxhx_bin, invalid_stdio_output, 64 * 1024 * 1024 + 1, "maximum is 67108864"
    )
    if invalid_stdio_output.exists():
        raise RuntimeError("rejected stdio frame unexpectedly produced target output")
    require_stdio_cancellation(hxhx_bin, fixture_root / "cancelled-stdio.js")
    require_stdio_shutdown(hxhx_bin, fixture_root / "shutdown-stdio.js")
    require_occupied_endpoint_is_left_alone(hxhx_bin, base_args)

    print(
        "HXHX_NATIVE_SERVER_CLIENT_OUTPUT_TIMING:"
        f"direct_ms={direct_elapsed_ms} "
        f"cold_ms={cold_elapsed_ms} "
        f"warm_ms={warm_elapsed_ms} "
        f"stability_min_ms={min(stability_elapsed_ms)} "
        f"stability_max_ms={max(stability_elapsed_ms)} "
        f"after_reset_ms={after_reset_elapsed_ms}"
    )
    print("HXHX_NATIVE_SERVER_CLIENT_OUTPUT_FIXTURE:PASS")
    return 0


